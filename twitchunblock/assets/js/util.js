/** Échappe une valeur avant de l'insérer dans du HTML.
 *  Titres de stream, pseudos et messages viennent de tiers : rien n'entre
 *  dans le DOM sans passer par ici. */
export function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[c])
}

export function uid() {
  if (globalThis.crypto?.randomUUID) return crypto.randomUUID()
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`
}

export const $ = (sel, root = document) => root.querySelector(sel)
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)]

export function debounce(fn, ms) {
  let t = null
  return (...args) => { clearTimeout(t); t = setTimeout(() => fn(...args), ms) }
}

export function formatViewers(n) {
  const v = Number(n) || 0
  if (v >= 1_000_000) return `${(v / 1_000_000).toFixed(1).replace(/\.0$/, '')}M`
  if (v >= 1000) return `${(v / 1000).toFixed(1).replace(/\.0$/, '')}k`
  return String(v)
}

/** 3725 → « 1:02:05 », 65 → « 1:05 ». */
export function formatClock(seconds) {
  const s = Math.max(0, Math.floor(Number(seconds) || 0))
  const h = Math.floor(s / 3600)
  const m = Math.floor((s % 3600) / 60)
  const sec = String(s % 60).padStart(2, '0')
  return h > 0 ? `${h}:${String(m).padStart(2, '0')}:${sec}` : `${m}:${sec}`
}

/** Durée d'une VOD en clair : « 3 h 12 » ou « 45 min ». */
export function formatDuration(seconds) {
  const s = Math.max(0, Math.floor(Number(seconds) || 0))
  const h = Math.floor(s / 3600)
  const m = Math.floor((s % 3600) / 60)
  return h > 0 ? `${h} h ${String(m).padStart(2, '0')}` : `${m} min`
}

export function uptimeSince(iso) {
  const start = Date.parse(iso)
  if (!Number.isFinite(start)) return ''
  return formatClock((Date.now() - start) / 1000)
}

export function thumb(url, w, h) {
  return String(url || '').replace('{width}', w).replace('{height}', h)
    .replace('%{width}', w).replace('%{height}', h)
}

